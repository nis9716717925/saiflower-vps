        echo "[ERR]  #{$num} '{$blog['title']}' — {$conn->error}\n";
        $errors++;
    }
    $stmt->close();
}
echo "\n=== SUMMARY ===\nInserted: {$inserted}\nSkipped:  {$skipped}\nErrors:   {$errors}\n\nDone! Batch 7 processed.\n";
